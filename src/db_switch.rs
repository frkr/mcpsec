/// Stamp the marker row into the SQLite settings table. Done after the
/// Postgres copy commits: a crash before this point leaves SQLite
/// unmarked and the whole operation retryable.
async fn mark_sqlite_superseded(
    sqlite: &DatabaseConnection,
    postgres_uri: &str,
) -> Result<(), String> {
    let settings = app_settings::Entity::find_by_id(SETTINGS_ID)
        .one(sqlite)
        .await
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "app_settings row missing".to_string())?;
    let mut am: app_settings::ActiveModel = settings.into();
    am.postgres_uri = Set(Some(postgres_uri.to_string()));
    am.migrated_to_postgres_at = Set(Some(chrono::Utc::now().into()));
    use sea_orm::ActiveModelTrait;
    ActiveModelTrait::update(am, sqlite)
        .await
        .map_err(|e| format!("could not write the sqlite marker: {e}"))?;
    Ok(())
}

/// Resolve the database URI at boot, BEFORE Loco connects.
///
/// Priority: `DATABASE_URL` env → marker row inside the SQLite file →
/// the YAML default (plain SQLite). The marker is read by opening the
/// SQLite file directly (cheap, read-only). When the marker URI is
/// returned, `fallback_uri` tells boot which SQLite URI to fall back to if
/// that Postgres is unreachable.
///
/// Returns `(uri, backend, degraded_fallback)`.
///
/// # Errors
/// Fails only when reading the SQLite settings table fails while a marker
/// read was otherwise possible; callers treat that as "stay on SQLite".
pub async fn resolve_boot_uri(default_uri: &str) -> Result<(String, Backend, bool), String> {
    // 1. Environment wins — an operator pinning DATABASE_URL means it.
    if let Ok(env_uri) = std::env::var("DATABASE_URL") {
        if !env_uri.trim().is_empty() && is_postgres_uri(&env_uri) {
            return Ok((env_uri, Backend::PostgresEnv, false));
        }
    }

    // 2. Marker row inside the SQLite file (only meaningful for sqlite
    //    defaults — reading a marker from a Postgres URI is nonsense).
    if !is_postgres_uri(default_uri) {
        match read_marker_from_sqlite(default_uri).await {
            Ok(Some((pg_uri, _migrated_at))) => {
                // Try Postgres now: reachable → use it.
                let mut opt = ConnectOptions::new(pg_uri.clone());
                opt.max_connections(2)
                    .min_connections(1)
                    .connect_timeout(std::time::Duration::from_secs(5));
                match Database::connect(opt).await {
                    Ok(probe) => {
                        drop(probe);
                        return Ok((pg_uri, Backend::PostgresSettings, false));
                    }
                    Err(e) => {
                        tracing::error!(
                            target = %redact_uri(&pg_uri),
                            error = %e,
                            "marked Postgres unreachable: falling back to the \
                             superseded SQLite file (data is stale)"
                        );
                        // 3. Degraded fallback on the stale SQLite file.
                        return Ok((default_uri.to_string(), Backend::Sqlite, true));
                    }
                }
            }
            Ok(None) => {}
            Err(e) => {
                tracing::warn!(error = %e, "could not read sqlite marker; staying on default");
            }
        }
    }

    Ok((default_uri.to_string(), Backend::Sqlite, false))
}

/// Read `(postgres_uri, migrated_at)` from the settings row of a SQLite
/// file, without booting Loco. `Ok(None)` = no marker.
async fn read_marker_from_sqlite(
    sqlite_uri: &str,
) -> Result<Option<(String, Option<chrono::DateTime<chrono::FixedOffset>>)>, String> {
    // A read-only open tolerates a missing file: no marker, no problem.
    if !sqlite_uri.contains("mode=rwc")
        && !std::path::Path::new(
            sqlite_uri
                .trim_start_matches("sqlite://")
                .split('?')
                .next()
                .unwrap_or(""),
        )
        .exists()
    {
        return Ok(None);
    }
    let mut opt = ConnectOptions::new(sqlite_uri.to_string());
    opt.max_connections(1)
        .min_connections(1)
        .connect_timeout(std::time::Duration::from_secs(5));
    let db = Database::connect(opt)
        .await
        .map_err(|e| format!("sqlite marker read: {e}"))?;
    let row = app_settings::Entity::find_by_id(SETTINGS_ID)
        .one(&db)
        .await
        .map_err(|e| format!("sqlite marker read: {e}"))?;
    Ok(row.and_then(|s| s.postgres_uri.map(|u| (u, s.migrated_to_postgres_at))))
}

