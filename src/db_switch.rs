//! SQLite → Postgres switchover.
//!
//! Flow (settings screen, `POST /api/settings/database`):
//!
//! 1. The handler connects to the requested Postgres URI, runs the migrator
//!    there and copies every business table inside **one Postgres
//!    transaction**. The target must be empty; ids are preserved and
//!    sequences are reset, so the copy is atomic and retry-safe.
//! 2. On success the handler stamps the marker into the SQLite file
//!    (`app_settings.postgres_uri` + `migrated_to_postgres_at`) and answers
//!    "restart to activate".
//! 3. The next boot resolves the database **before** Loco connects
//!    (see [`resolve_boot_uri`]): `DATABASE_URL` env wins; else the marker
//!    row inside the SQLite file is read and its Postgres URI replaces the
//!    config URI; else SQLite stays. If the marked Postgres is unreachable,
//!    the app still boots on the stale SQLite file flagged degraded
//!    (see [`degraded::is_read_only`]) so stale security state is never
//!    presented as live.
//!
//! Writes that happen between the copy and the restart stay in SQLite and
//! are lost on activation; the settings UI warns about this and the
//! migration result includes `restart_required`. Copying `tool_calls`
//! (audit history) is deliberate: a security product must not silently
//! drop its audit trail on a database switch. Only the TTL'd proxy
//! sessions/grants are not copied — they are live runtime state and die
//! at cutover by design.

