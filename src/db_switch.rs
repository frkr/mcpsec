/// Batch size for chunked inserts. Small enough that
/// `rows × columns` stays far below Postgres' 65,535 bind-parameter limit
/// (the widest table here has ~15 columns).
const COPY_BATCH: usize = 500;

/// Boot-time snapshot of which database was selected and how.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DbState {
    /// Which backend the process is actually using.
    pub backend: Backend,
    /// True when booting on a marked-superseded SQLite file because the
    /// configured Postgres was unreachable. Data is stale.
    pub degraded_fallback: bool,
}

/// Which backend the running process uses.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Backend {
    /// Default: nothing configured, plain SQLite.
    Sqlite,
    /// `DATABASE_URL` env var pointing at Postgres.
    PostgresEnv,
    /// Activated from the settings screen (marker row in the old SQLite
    /// file resolved at boot).
    PostgresSettings,
}

impl Backend {
    #[must_use]
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Sqlite => "sqlite",
            Self::PostgresEnv => "postgres-env",
            Self::PostgresSettings => "postgres-settings",
        }
    }
}

static DB_STATE: OnceLock<DbState> = OnceLock::new();

/// The boot-time database decision. Set once during boot.
///
/// # Panics
/// When called before boot initialized it (programming error).
#[must_use]
pub fn state() -> DbState {
    *DB_STATE
        .get()
        .expect("db_switch::state() called before boot initialized it")
}

/// Publish the boot-time decision (called once, from boot).
///
/// # Errors
/// Returns an error when called twice.
pub fn init(state: DbState) -> Result<(), String> {
    DB_STATE
        .set(state)
        .map_err(|_| "db_switch::init called twice".to_string())
}

/// Degraded-mode gate: set when the process fell back to a superseded
/// SQLite file. While set, mutating endpoints must refuse writes.
pub mod degraded {
    use super::*;

    static DEGRADED: OnceLock<bool> = OnceLock::new();

    /// Whether the process booted on a superseded SQLite fallback.
    #[must_use]
    pub fn is_active() -> bool {
        *DEGRADED.get().unwrap_or(&false)
    }

    /// Publish the degraded flag (called once, from boot).
    pub fn set(value: bool) {
        let _ = DEGRADED.set(value);
    }
}

/// Mask the password of a database URI for display/logging.
/// `postgres://user:secret@host/db` → `postgres://user:***@host/db`.
#[must_use]
pub fn redact_uri(uri: &str) -> String {
    let Some(scheme_end) = uri.find("://") else {
        return uri.to_string();
    };
    let rest = &uri[scheme_end + 3..];
    let Some(at) = rest.find('@') else {
        return uri.to_string();
    };
    let userinfo = &rest[..at];
    if let Some(colon) = userinfo.find(':') {
        format!(
            "{}://{}:***@{}",
            &uri[..scheme_end],
            &userinfo[..colon],
            &rest[at + 1..]
        )
    } else {
        uri.to_string()
    }
}

/// Does the URI point at Postgres?
#[must_use]
pub fn is_postgres_uri(uri: &str) -> bool {
    uri.starts_with("postgres://") || uri.starts_with("postgresql://")
}

/// Result of a migration run from the settings screen.
#[derive(Debug, Serialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct MigrationResult {
    pub ok: bool,
    /// Rows copied per table.
    #[ts(type = "Record<string, number>")]
    pub copied: BTreeMap<String, i64>,
    /// Always true: the operator must restart the process to switch over.
    pub restart_required: bool,
    pub message: String,
}

/// `POST /api/settings/database` params.
#[derive(Debug, Deserialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct DatabaseSwitchParams {
    /// Full Postgres URI, e.g. `postgres://user:pass@host:5432/mcpsec`.
    pub postgres_uri: String,
}

/// What `GET /api/settings/database` reports.
#[derive(Debug, Serialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct DatabaseStatus {
    /// `sqlite` | `postgres-env` | `postgres-settings`.
    pub backend: String,
    /// Redacted URI of the active database.
    pub active_uri: String,
    /// True when a migration has completed and this process still runs on
    /// the old (now superseded) SQLite file.
    pub restart_required: bool,
    /// True when running on the superseded SQLite fallback (Postgres down).
    pub degraded_fallback: bool,
    /// Postgres URI previously configured in the settings screen (redacted).
    pub configured_postgres_uri: Option<String>,
    /// When the SQLite → Postgres copy committed.
    pub migrated_to_postgres_at: Option<String>,
}

/// Entry point for the settings screen: copy SQLite → Postgres and mark the
/// SQLite file as superseded.
///
/// # Errors
/// Errors (as strings, mapped to 400 by the caller) when the URI is not
/// Postgres, the target is unreachable or not empty, or the copy/marker
/// write fails. The Postgres URI is never echoed back verbatim.
pub async fn switch_to_postgres(
    sqlite: &DatabaseConnection,
    params: &DatabaseSwitchParams,
) -> Result<MigrationResult, String> {
    if !is_postgres_uri(&params.postgres_uri) {
        return Err("postgres_uri deve começar com postgres:// ou postgresql://".into());
    }

    let mut opt = ConnectOptions::new(params.postgres_uri.clone());
    opt.max_connections(2)
        .min_connections(1)
        .connect_timeout(std::time::Duration::from_secs(5));

    let pg = Database::connect(opt)
        .await
        .map_err(|e| format!("não consegui conectar no Postgres: {e}"))?;

    Migrator::up(&pg, None)
        .await
        .map_err(|e| format!("migração no Postgres falhou: {e}"))?;

    let copied = copy_sqlite_to_postgres(sqlite, &pg).await?;

    // Marker: this SQLite file is superseded. Written AFTER the copy
    // commits; the next boot reads it and switches to Postgres.
    mark_sqlite_superseded(sqlite, &params.postgres_uri).await?;

    tracing::info!(
        target = %redact_uri(&params.postgres_uri),
        copied = ?copied,
        "sqlite → postgres copy committed; restart to activate"
    );

    Ok(MigrationResult {
        ok: true,
        copied,
        restart_required: true,
        message: "Dados copiados para o Postgres. Reinicie o processo para ativar.".to_string(),
    })
}

/// Copy every business table SQLite → Postgres inside one Postgres
/// transaction, preserving ids and resetting sequences. The target must be
/// empty (fresh migrate or an aborted previous attempt — nothing partial is
/// ever left behind because everything is in one transaction).
async fn copy_sqlite_to_postgres(
    sqlite: &DatabaseConnection,
    pg: &DatabaseConnection,
) -> Result<BTreeMap<String, i64>, String> {
    let txn = pg
        .begin()
        .await
        .map_err(|e| format!("falha ao abrir transação no Postgres: {e}"))?;

    let run = async {
        let mut copied = BTreeMap::new();

        // FK order: users → app_settings → mcp_servers → mcp_tools →
        // sync_runs → tool_calls.
        copied.insert("users".into(), copy_users(sqlite, &txn).await? as i64);
        copied.insert(
            "app_settings".into(),
            copy_app_settings(sqlite, &txn).await? as i64,
        );
        copied.insert(
            "mcp_servers".into(),
            copy_mcp_servers(sqlite, &txn).await? as i64,
        );
        copied.insert(
            "mcp_tools".into(),
            copy_mcp_tools(sqlite, &txn).await? as i64,
        );
        copied.insert(
            "sync_runs".into(),
            copy_sync_runs(sqlite, &txn).await? as i64,
        );
        copied.insert(
            "tool_calls".into(),
            copy_tool_calls(sqlite, &txn).await? as i64,
        );

        // Preserve id continuity: without this, the first insert after the
        // cutover hits a duplicate key on every copied table.
        for table in [
            "users",
            "app_settings",
            "mcp_servers",
            "mcp_tools",
            "sync_runs",
            "tool_calls",
        ] {
            let stmt = sea_orm::Statement::from_string(
                sea_orm::DatabaseBackend::Postgres,
                format!(
                    "SELECT setval(pg_get_serial_sequence('{table}', 'id'), \
                     COALESCE((SELECT MAX(id) FROM {table}), 1))"
                ),
            );
            txn.query_all_raw(stmt)
                .await
                .map_err(|e| format!("could not reset sequence of {table}: {e}"))?;
        }

        Ok::<BTreeMap<String, i64>, String>(copied)
    };

    let copied = match run.await {
        Ok(copied) => {
            txn.commit()
                .await
                .map_err(|e| format!("falha ao commitar cópia no Postgres: {e}"))?;
            copied
        }
        Err(e) => {
            let _ = txn.rollback().await;
            return Err(e);
        }
    };

    Ok(copied)
}

/// Guard: the Postgres target table must be empty before copying.
async fn assert_empty(
    txn: &sea_orm::DatabaseTransaction,
    table: &'static str,
) -> Result<(), String> {
    let stmt = sea_orm::Statement::from_string(
        sea_orm::DatabaseBackend::Postgres,
        format!("SELECT COUNT(*) FROM {table}"),
    );
    let rows = txn
        .query_all_raw(stmt)
        .await
        .map_err(|e| format!("could not count {table}: {e}"))?;
    let count: i64 = rows
        .first()
        .and_then(|r| r.try_get::<i64>("", "count").ok())
        .unwrap_or(0);
    if count > 0 {
        return Err(format!(
            "tabela {table} no Postgres não está vazia ({count} linhas); \
             use um banco limpo"
        ));
    }
    Ok(())
}

async fn copy_users(
    sqlite: &DatabaseConnection,
    txn: &sea_orm::DatabaseTransaction,
) -> Result<u64, String> {
    assert_empty(txn, "users").await?;
    let rows = users::Entity::find()
        .order_by_asc(users::Column::Id)
        .all(sqlite)
        .await
        .map_err(|e| e.to_string())?;
    for chunk in rows.chunks(COPY_BATCH) {
        let models: Vec<users::ActiveModel> = chunk
            .iter()
            .map(|u| users::ActiveModel {
                created_at: Set(u.created_at),
                updated_at: Set(u.updated_at),
                id: Set(u.id),
                pid: Set(u.pid),
                email: Set(u.email.clone()),
                password: Set(u.password.clone()),
                api_key: Set(u.api_key.clone()),
                name: Set(u.name.clone()),
                role: Set(u.role.clone()),
                reset_token: Set(u.reset_token.clone()),
                reset_sent_at: Set(u.reset_sent_at),
                email_verification_token: Set(u.email_verification_token.clone()),
                email_verification_sent_at: Set(u.email_verification_sent_at),
                email_verified_at: Set(u.email_verified_at),
                magic_link_token: Set(u.magic_link_token.clone()),
                magic_link_expiration: Set(u.magic_link_expiration),
            })
            .collect();
        users::Entity::insert_many(models)
            .exec(txn)
            .await
            .map_err(|e| format!("insert users: {e}"))?;
    }
    Ok(rows.len() as u64)
}

