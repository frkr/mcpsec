/// Server lifecycle states, stored as strings in `mcp_servers.lifecycle`.
///
/// ```text
///            ┌──────────┐  activate   ┌────────────────┐ approve ┌────────┐
/// registry ─►│   new    │────────────►│ awaiting_review│────────►│ active │
///  sync      └──────────┘             └───────┬────────┘         └───┬────┘
///                                            │ reject               │ disable
///                                            ▼                      ▼
///                                        rejected ◄──────────── disabled
/// ```
/// Rejected and disabled servers can be re-activated at any time; `activate`
/// always re-enters the workflow. `activating` is the transient state while
/// the discovery worker probes the remote endpoint.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lifecycle {
    /// Imported from the registry, never touched by a user.
    New,
    /// Activation workflow running: the worker is probing the remote MCP.
    Activating,
    /// Tools discovered and labelled; waiting for human review.
    AwaitingReview,
    /// Approved and runnable through the proxy.
    Active,
    /// User declined activation.
    Rejected,
    /// Previously active, later turned off.
    Disabled,
}

impl Lifecycle {
    #[must_use]
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::New => "new",
            Self::Activating => "activating",
            Self::AwaitingReview => "awaiting_review",
            Self::Active => "active",
            Self::Rejected => "rejected",
            Self::Disabled => "disabled",
        }
    }

    #[must_use]
    pub fn parse(s: &str) -> Self {
        match s {
            "activating" => Self::Activating,
            "awaiting_review" => Self::AwaitingReview,
            "active" => Self::Active,
            "rejected" => Self::Rejected,
            "disabled" => Self::Disabled,
            _ => Self::New,
        }
    }

    /// A server is runnable only in the `active` state.
    #[must_use]
    pub fn is_runnable(&self) -> bool {
        matches!(self, Self::Active)
    }
}

/// The three tool risk labels, rendered as badges in the UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ToolCategory {
    ReadOnly,
    Write,
    Admin,
}

impl ToolCategory {
    #[must_use]
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::ReadOnly => "READ_ONLY",
            Self::Write => "WRITE",
            Self::Admin => "ADMIN",
        }
    }

    #[must_use]
    pub fn parse(s: &str) -> Self {
        match s {
            "WRITE" => Self::Write,
            "ADMIN" => Self::Admin,
            _ => Self::ReadOnly,
        }
    }
}

/// Registry metadata refresh, applied by the sync service. Sync never touches
/// the lifecycle: it only refreshes registry fields and the endpoint.
#[derive(Debug)]
pub struct RegistryUpsert {
    pub registry_name: String,
    pub title: String,
    pub description: Option<String>,
    pub version: String,
    pub remote_url: String,
    pub remote_type: String,
    pub registry_status: String,
    pub registry_published_at: Option<DateTimeWithTimeZone>,
    pub registry_updated_at: Option<DateTimeWithTimeZone>,
    pub is_latest: bool,
}

impl Model {
    /// Find the row imported from the registry under `registry_name`.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn find_by_registry_name(
        db: &DatabaseConnection,
        registry_name: &str,
    ) -> Result<Option<Model>, DbErr> {
        Entity::find()
            .filter(mcp_servers::Column::RegistryName.eq(registry_name))
            .one(db)
            .await
    }

    /// All servers ordered by registry name.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn list_all(db: &DatabaseConnection) -> Result<Vec<Model>, DbErr> {
        Entity::find()
            .order_by_asc(mcp_servers::Column::RegistryName)
            .all(db)
            .await
    }

    /// Servers that passed the activation workflow and are runnable.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn list_active(db: &DatabaseConnection) -> Result<Vec<Model>, DbErr> {
        Entity::find()
            .filter(mcp_servers::Column::Lifecycle.eq(Lifecycle::Active.as_str()))
            .order_by_asc(mcp_servers::Column::RegistryName)
            .all(db)
            .await
    }

    /// Servers in the activation queue: review pending, or discovery stuck
    /// (`activating` rows whose worker died are re-picked here).
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn list_pending(db: &DatabaseConnection) -> Result<Vec<Model>, DbErr> {
        Entity::find()
            .filter(mcp_servers::Column::Lifecycle.is_in([
                Lifecycle::Activating.as_str(),
                Lifecycle::AwaitingReview.as_str(),
            ]))
            .order_by_asc(mcp_servers::Column::Id)
            .all(db)
            .await
    }
}

impl ActiveModel {
    /// Insert-or-refresh a registry entry. New servers start `new` +
    /// disabled; existing servers keep their lifecycle and only get fresh
    /// registry metadata and endpoint.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn upsert_from_registry(
        db: &DatabaseConnection,
        data: &RegistryUpsert,
    ) -> Result<(Model, bool), DbErr> {
        match Model::find_by_registry_name(db, &data.registry_name).await? {
            Some(existing) => {
                let mut am: ActiveModel = existing.into();
                am.title = Set(data.title.clone());
                am.description = Set(data.description.clone());
                am.version = Set(data.version.clone());
                am.remote_url = Set(data.remote_url.clone());
                am.remote_type = Set(data.remote_type.clone());
                am.registry_status = Set(data.registry_status.to_string());
                am.registry_published_at = Set(data.registry_published_at);
                am.registry_updated_at = Set(data.registry_updated_at);
                am.is_latest = Set(Some(data.is_latest));
                let saved = am.update(db).await?;
                Ok((saved, false))
            }
            None => {
                let am = ActiveModel {
                    registry_name: Set(data.registry_name.clone()),
                    title: Set(data.title.clone()),
                    description: Set(data.description.clone()),
                    version: Set(data.version.clone()),
                    remote_url: Set(data.remote_url.clone()),
                    remote_type: Set(data.remote_type.clone()),
                    registry_status: Set(data.registry_status.to_string()),
                    registry_published_at: Set(data.registry_published_at),
                    registry_updated_at: Set(data.registry_updated_at),
                    is_latest: Set(Some(data.is_latest)),
                    sync_source: Set("registry".to_string()),
                    lifecycle: Set(Lifecycle::New.as_str().to_string()),
                    enabled: Set(false),
                    last_error: Set(None),
                    ..Default::default()
                };
                let saved = am.insert(db).await?;
                Ok((saved, true))
            }
        }
    }

    /// Enter the activation workflow (`activating`). Only non-active servers
    /// may start; re-activation from `rejected`/`disabled` is allowed.
    ///
    /// # Errors
    /// Returns [`DbErr`] on query failure or when the transition is invalid.
    pub async fn start_activation(self, db: &DatabaseConnection) -> Result<Model, DbErr> {
        let lifecycle = Lifecycle::parse(self.lifecycle.as_ref());
        if lifecycle.is_runnable() {
            return Err(DbErr::Custom("server already active".into()));
        }
        let mut am = self;
        am.lifecycle = Set(Lifecycle::Activating.as_str().to_string());
        am.enabled = Set(false);
        am.last_error = Set(None);
        am.update(db).await
    }

    /// Discovery finished: store results and move to `awaiting_review`.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn finish_activation(self, db: &DatabaseConnection) -> Result<Model, DbErr> {
        let mut am = self;
        am.lifecycle = Set(Lifecycle::AwaitingReview.as_str().to_string());
        am.update(db).await
    }

    /// Discovery failed: back to `new`, recording the error for the UI.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn fail_activation(
        self,
        db: &DatabaseConnection,
        error: &str,
    ) -> Result<Model, DbErr> {
        let mut am = self;
        am.lifecycle = Set(Lifecycle::New.as_str().to_string());
        am.last_error = Set(Some(error.to_string()));
        am.update(db).await
    }

    /// Approve the review: the server becomes runnable.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn approve(self, db: &DatabaseConnection, by: &str) -> Result<Model, DbErr> {
        let mut am = self;
        am.lifecycle = Set(Lifecycle::Active.as_str().to_string());
        am.enabled = Set(true);
        am.activated_by = Set(Some(by.to_string()));
        am.activated_at = Set(Some(Utc::now().into()));
        am.last_error = Set(None);
        am.update(db).await
    }

    /// Reject the review.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn reject(self, db: &DatabaseConnection, by: &str) -> Result<Model, DbErr> {
        let mut am = self;
        am.lifecycle = Set(Lifecycle::Rejected.as_str().to_string());
        am.enabled = Set(false);
        am.deactivated_by = Set(Some(by.to_string()));
        am.deactivated_at = Set(Some(Utc::now().into()));
        am.update(db).await
    }

    /// Turn a previously active server off.
    ///
    /// # Errors
    /// Returns [`DbErr`] when the query fails.
    pub async fn disable(self, db: &DatabaseConnection, by: &str) -> Result<Model, DbErr> {
        let mut am = self;
        am.lifecycle = Set(Lifecycle::Disabled.as_str().to_string());
        am.enabled = Set(false);
        am.deactivated_by = Set(Some(by.to_string()));
        am.deactivated_at = Set(Some(Utc::now().into()));
        am.update(db).await
    }
}

impl Model {
    /// The current lifecycle as an enum.
    #[must_use]
    pub fn lifecycle(&self) -> Lifecycle {
        Lifecycle::parse(&self.lifecycle)
    }
}

#[async_trait::async_trait]
impl ActiveModelBehavior for ActiveModel {
    async fn before_save<C>(self, _db: &C, insert: bool) -> Result<Self, DbErr>
    where
        C: ConnectionTrait,
    {
        if !insert && self.updated_at.is_unchanged() {
            let mut this = self;
            this.updated_at = Set(chrono::Utc::now().into());
            Ok(this)
        } else {
            Ok(self)
        }
    }
}

/// One page of the registry listing plus the totals the UI needs.
#[derive(Debug)]
pub struct ServerPage {
    pub items: Vec<Model>,
    pub page: u64,
    pub page_size: u64,
    pub total_items: u64,
    pub total_pages: u64,
    /// Total matching the *text* filter only, ignoring `lifecycle`. This is
    /// what the "Todos" option in the lifecycle combo must show.
    pub filtered_items: u64,
    /// Row count per lifecycle, ignoring the lifecycle filter (for the tabs).
    pub counts: std::collections::BTreeMap<String, i64>,
}

impl Model {
    /// Paginated, filtered listing.
    ///
    /// `q` matches registry name, title and description; `lifecycle` narrows
    /// by state. Pages are 1-based and clamped to the result set, so an
    /// out-of-range page returns the last one instead of an empty table.
    ///
    /// Three totals are reported because the UI needs all of them:
    ///
    /// - `total_items` — rows matching *text + lifecycle* (the table pager).
    /// - `filtered_items` — rows matching the *text* filter only; this is what
    ///   the "Todos" option in the lifecycle combo must display, otherwise
    ///   picking a status silently rewrites the "Todos" number.
    /// - `counts` — per-lifecycle rows under the text filter (combo labels).
    ///
    /// # Errors
    /// Returns [`DbErr`] when a query fails.
    pub async fn paginate(
        db: &DatabaseConnection,
        q: Option<&str>,
        lifecycle: Option<&str>,
        page: u64,
        page_size: u64,
    ) -> Result<ServerPage, DbErr> {
        use sea_orm::{FromQueryResult, QuerySelect};

        let page_size = page_size.clamp(1, 200);
        let term = q
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(str::to_string);
        let state = lifecycle
            .map(str::trim)
            .filter(|s| !s.is_empty() && *s != "all")
            .map(str::to_string);

        // Text filter shared by every query below. `like()` emits no ESCAPE
        // clause, so nothing is escaped on purpose: an escaped `\_` would
        // match a literal backslash and return zero rows for names such as
        // "docs_mcp". Treating `_`/`%` as wildcards is the better UX here.
        let text_filter = || {
            let mut cond = sea_orm::Condition::any();
            if let Some(term) = &term {
                let like = format!("%{term}%");
                cond = cond
                    .add(mcp_servers::Column::RegistryName.like(&like))
                    .add(mcp_servers::Column::Title.like(&like))
                    .add(mcp_servers::Column::Description.like(&like));
            }
            cond
        };

        let scoped = || {
            let mut query = Entity::find();
            if term.is_some() {
                query = query.filter(text_filter());
            }
            if let Some(state) = &state {
                query = query.filter(mcp_servers::Column::Lifecycle.eq(state.as_str()));
            }
            query
        };

        let total_items = scoped().count(db).await?;
        let total_pages = total_items.div_ceil(page_size).max(1);
        let page = page.max(1).min(total_pages);
        let items = scoped()
            .order_by_asc(mcp_servers::Column::RegistryName)
            .offset((page - 1) * page_size)
            .limit(page_size)
            .all(db)
            .await?;

        // One GROUP BY instead of one COUNT per lifecycle.
        #[derive(Debug, FromQueryResult)]
        struct LifecycleCount {
            lifecycle: String,
            total: i64,
        }
        let mut grouped = Entity::find()
            .select_only()
            .column(mcp_servers::Column::Lifecycle)
            .column_as(mcp_servers::Column::Id.count(), "total")
            .group_by(mcp_servers::Column::Lifecycle);
        if term.is_some() {
            grouped = grouped.filter(text_filter());
        }
        let rows = grouped
            .into_model::<LifecycleCount>()
            .all(db)
            .await
            .unwrap_or_default();

        let mut counts: std::collections::BTreeMap<String, i64> = std::collections::BTreeMap::new();
        for st in [
            Lifecycle::New,
            Lifecycle::Activating,
            Lifecycle::AwaitingReview,
            Lifecycle::Active,
            Lifecycle::Rejected,
            Lifecycle::Disabled,
        ] {
            counts.insert(st.as_str().to_string(), 0);
        }
        for row in rows {
            counts.insert(row.lifecycle, row.total);
        }

        // Text-only total: the combo's "Todos" option.
        let filtered_items = if state.is_some() {
            let mut query = Entity::find();
            if term.is_some() {
                query = query.filter(text_filter());
            }
            query.count(db).await?
        } else {
            total_items
        };

        Ok(ServerPage {
            items,
            page,
            page_size,
            total_items,
            total_pages,
            filtered_items,
            counts,
        })
    }
}
