//! Minimal MCP client over Streamable HTTP (JSON-RPC 2.0).
//!
//! Implements exactly what this app needs: `initialize`, `tools/list`,
//! `tools/call` — plus the `Mcp-Session-Id` session dance and an SSE body
//! fallback (`text/event-stream`) used by servers that stream responses.

use serde_json::{json, Value};
use tokio::sync::Mutex;

const PROTOCOL_VERSION: &str = "2025-06-18";
const CLIENT_INFO: (&str, &str) = ("mcpsec", env!("CARGO_PKG_VERSION"));

/// One live session against one MCP server endpoint.
pub struct McpClient {
    http: reqwest::Client,
    url: String,
    session: Mutex<Option<String>>,
}

impl McpClient {
    /// Build a client for a streamable-http endpoint.
    ///
    /// Remote URLs come from registry data — user-influenced input — so the
    /// guard rejects anything that is not https, any host that resolves to a
    /// loopback/private/link-local address, and any explicit port onto
    /// private ranges. This is the SSRF fence for the proxy.
    ///
    /// # Errors
    /// Returns an error when the URL is unsafe or the HTTP client cannot be
    /// built.
    pub fn new(url: &str, timeout: std::time::Duration) -> Result<Self, String> {
        ssrf_guard(url)?;
        let http = reqwest::Client::builder()
            .timeout(timeout)
            .redirect(reqwest::redirect::Policy::limited(5))
            .build()
            .map_err(|e| format!("http client: {e}"))?;
        Ok(Self {
            http,
            url: url.to_string(),
            session: Mutex::new(None),
        })
    }

    async fn post(&self, body: Value, expect_response: bool) -> Result<Option<Value>, String> {
        let session = self.session.lock().await.clone();
        let mut req = self
            .http
            .post(&self.url)
            .header("Accept", "application/json, text/event-stream")
            .header("MCP-Protocol-Version", PROTOCOL_VERSION)
            .json(&body);
        if let Some(sid) = session {
            req = req.header("Mcp-Session-Id", sid);
        }
        let resp = req
            .send()
            .await
            .map_err(|e| format!("request failed: {e}"))?;
        let status = resp.status();
        let sid = resp
            .headers()
            .get("mcp-session-id")
            .and_then(|v| v.to_str().ok())
            .map(str::to_string);
        if let Some(sid) = sid {
            *self.session.lock().await = Some(sid);
        }
        if !status.is_success() {
            let body = resp.text().await.unwrap_or_default();
            return Err(format!("http {status}: {}", truncate(&body, 300)));
        }
        if !expect_response {
            return Ok(None);
        }

        let content_type = resp
            .headers()
            .get("content-type")
            .and_then(|v| v.to_str().ok())
            .unwrap_or("")
            .to_ascii_lowercase();
        if content_type.contains("text/event-stream") {
            let text = resp.text().await.map_err(|e| format!("sse read: {e}"))?;
            let payload = parse_sse(&text);
            return Ok(payload);
        }
        let text = resp.text().await.map_err(|e| format!("body read: {e}"))?;
        if text.is_empty() {
            return Ok(None);
        }
        let value: Value = serde_json::from_str(&text).map_err(|e| format!("body parse: {e}"))?;
        Ok(Some(value))
    }

    async fn request(&self, method: &str, params: Value, id: i64) -> Result<Value, String> {
        let body = json!({
            "jsonrpc": "2.0",
            "id": id,
            "method": method,
            "params": params,
        });
        let payload = self.post(body, true).await?;
        let payload = payload.ok_or_else(|| "empty response from MCP server".to_string())?;
        if let Some(err) = payload.get("error") {
            return Err(format!(
                "rpc {}: {}",
                err.get("code").and_then(Value::as_i64).unwrap_or(-32603),
                err.get("message")
                    .and_then(Value::as_str)
                    .unwrap_or("unknown error")
            ));
        }
        Ok(payload.get("result").cloned().unwrap_or(Value::Null))
    }

    async fn notify(&self, method: &str, params: Value) -> Result<(), String> {
        let body = json!({
            "jsonrpc": "2.0",
            "method": method,
            "params": params,
        });
        self.post(body, false).await?;
        Ok(())
    }

    /// Initialize a session and send the required `notifications/initialized`.
    ///
    /// # Errors
    /// Returns a string describing any transport or protocol failure.
    pub async fn initialize(&self) -> Result<Value, String> {
        let result = self
            .request(
                "initialize",
                json!({
                    "protocolVersion": PROTOCOL_VERSION,
                    "capabilities": {},
                    "clientInfo": {"name": CLIENT_INFO.0, "version": CLIENT_INFO.1},
                }),
                1,
            )
            .await?;
        self.notify("notifications/initialized", json!({}))
            .await
            // Servers that do not care about the notification still accepted
            // the initialize; keep going either way.
            .unwrap_or(());
        Ok(result)
    }

    /// List the remote server's tools.
    ///
    /// # Errors
    /// Returns a string describing any transport or protocol failure.
    pub async fn list_tools(&self) -> Result<Vec<Value>, String> {
        let mut tools = Vec::new();
        let mut cursor: Option<String> = None;
        loop {
            let mut params = json!({});
            if let Some(c) = &cursor {
                params["cursor"] = Value::String(c.clone());
            }
            let result = self.request("tools/list", params, 2).await?;
            if let Some(list) = result.get("tools").and_then(Value::as_array) {
                tools.extend(list.iter().cloned());
            }
            cursor = result
                .get("nextCursor")
                .and_then(Value::as_str)
                .filter(|c| !c.is_empty())
                .map(str::to_string);
            if cursor.is_none() || tools.len() > 5_000 {
                break;
            }
        }
        Ok(tools)
    }

    /// Call one tool by name with JSON arguments.
    ///
    /// # Errors
    /// Returns a string describing any transport or protocol failure.
    pub async fn call_tool(&self, name: &str, arguments: Value) -> Result<Value, String> {
        self.request(
            "tools/call",
            json!({"name": name, "arguments": arguments}),
            3,
        )
        .await
    }
}

/// Extract the first JSON-RPC payload from an SSE body: lines of
/// `data: {...}` until a complete object is seen.
fn parse_sse(text: &str) -> Option<Value> {
    let mut data = String::new();
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("data:") {
            data.push_str(rest.trim_start());
            data.push('\n');
        } else if line.is_empty() && !data.trim().is_empty() {
            if let Ok(v) = serde_json::from_str::<Value>(data.trim()) {
                return Some(v);
            }
            data.clear();
        }
    }
    if data.trim().is_empty() {
        None
    } else {
        serde_json::from_str(data.trim()).ok()
    }
}

fn truncate(s: &str, max: usize) -> String {
    if s.len() <= max {
        s.to_string()
    } else {
        format!("{}…", &s[..max])
    }
}

/// Reject non-https URLs and hosts that look local or private. DNS-level
/// rebinding is out of scope for this fence; the hostname literal check plus
/// https enforcement blocks the realistic vectors (localhost, 169.254
/// metadata services, RFC1918 hosts, plain-http exfiltration).
///
/// Shared by the MCP client and by the custom-server CRUD, so a URL refused at
/// the moment it is saved is the same one the activation worker would refuse
/// later — the two must never diverge.
///
/// # Errors
/// Returns a human-readable reason when the URL is unsafe to dial.
pub(crate) fn ssrf_guard(url: &str) -> Result<(), String> {
    let parsed = url::Url::parse(url).map_err(|e| format!("invalid remote url: {e}"))?;
    if parsed.scheme() != "https" {
        return Err(format!(
            "remote url must be https, got '{}'",
            parsed.scheme()
        ));
    }
    let Some(host) = parsed.host_str() else {
        return Err("remote url has no host".to_string());
    };
    let host_lower = host.to_ascii_lowercase();
    if matches!(
        host_lower.as_str(),
        "localhost" | "127.0.0.1" | "0.0.0.0" | "::1" | "[::1]"
    ) || host_lower.ends_with(".localhost")
        || host_lower.ends_with(".local")
        || host_lower.ends_with(".internal")
    {
        return Err(format!("remote host '{host}' is not allowed"));
    }
    if let Ok(ip) = host_lower.parse::<std::net::IpAddr>() {
        let blocked = match ip {
            std::net::IpAddr::V4(v4) => {
                v4.is_loopback() || v4.is_private() || v4.is_link_local() || v4.is_unspecified()
            }
            std::net::IpAddr::V6(v6) => v6.is_loopback() || v6.is_unspecified(),
        };
        if blocked {
            return Err(format!("remote ip '{host}' is not allowed"));
        }
    }
    Ok(())
}
