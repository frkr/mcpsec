//! Degraded-mode write gate.
//!
//! When the process boots on a superseded SQLite file because the configured
//! Postgres is unreachable, writes to it would be discarded at activation
//! time. This axum middleware turns mutating requests (POST/PUT/PATCH/DELETE)
//! on application routes into `503 Service Unavailable` with a clear
//! message. Reads stay open so the operator can inspect the stale state and
//! the settings screen stays reachable for diagnostics.

use axum::http::{Method, StatusCode};
use axum::response::IntoResponse;

/// HTTP methods that change state.
fn is_mutating(method: &Method) -> bool {
    matches!(
        *method,
        Method::POST | Method::PUT | Method::PATCH | Method::DELETE
    )
}

/// Paths that must keep working even degraded (they do not write business
/// data): the status endpoint and the auth endpoints used to log in and see
/// what is happening.
fn is_exempt(path: &str) -> bool {
    path.starts_with("/api/settings/database")
        || path.starts_with("/api/auth/")
        || path.starts_with("/_auth")
        || path.starts_with("/mcp/")
        || path.starts_with("/api/sync")
        || path == "/"
}

/// The axum middleware body: block writes when degraded mode is active.
pub async fn guard(
    req: axum::extract::Request,
    next: axum::middleware::Next,
) -> axum::response::Response {
    if crate::db_switch::degraded::is_active()
        && is_mutating(req.method())
        && !is_exempt(req.uri().path())
    {
        return (
            StatusCode::SERVICE_UNAVAILABLE,
            [(axum::http::header::CONTENT_TYPE, "application/json")],
            serde_json::json!({
                "code": "degraded_read_only",
                "message": "O banco configurado (Postgres) está inacessível; \
                            o sistema está em modo degradado num arquivo SQLite \
                            antigo. As escritas estão bloqueadas para não criar \
                            dados que seriam descartados. Corrija a conexão e \
                            reinicie."
            })
            .to_string(),
        )
            .into_response();
    }
    next.run(req).await
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mutating_methods_detected() {
        assert!(is_mutating(&Method::POST));
        assert!(is_mutating(&Method::DELETE));
        assert!(!is_mutating(&Method::GET));
        assert!(!is_mutating(&Method::HEAD));
    }

    #[test]
    fn exempt_paths_do_not_block() {
        assert!(is_exempt("/api/settings/database"));
        assert!(is_exempt("/api/auth/login"));
        assert!(is_exempt("/api/sync"));
        assert!(is_exempt("/mcp/"));
        assert!(!is_exempt("/api/servers/1/activate"));
        assert!(!is_exempt("/api/settings"));
    }
}
