async fn handle_tools_list(
    ctx: &AppContext,
    headers: &axum::http::HeaderMap,
    id: Value,
) -> Response {
    // Without a valid session the surface is deliberately minimal: only the
    // onboarding bridge. No catalog, no tool names, nothing else leaks.
    let Some(session) = auth_session(ctx, headers).await else {
        return rpc_http(ok_response(id, json!({ "tools": [make_auth_tool()] })));
    };
    let granted = mcp_proxy_grants::ActiveModel::live_for_session(&ctx.db, session.id)
        .await
        .unwrap_or_default();

    let mut tools = builtin_tools();
    for (_grant, tool) in granted {
        let server_name = mcp_servers::Entity::find_by_id(tool.mcp_server_id)
            .one(&ctx.db)
            .await
            .ok()
            .flatten()
            .map(|s| s.registry_name)
            .unwrap_or_else(|| format!("server-{}", tool.mcp_server_id));
        tools.push(json!({
            "name": tool.tool_name,
            "description": tool.description.clone().unwrap_or_default(),
            "inputSchema": tool.input_schema.clone().unwrap_or(json!({"type":"object","properties":{}})),
            // mcpsec extensions so agents can keep provenance straight.
            "annotations": {
                "mcpsec:category": tool.category,
                "mcpsec:server": server_name,
            },
        }));
    }
    rpc_http(ok_response(id, json!({ "tools": tools })))
}

// --------------------------------------------------------------- tools/call

async fn handle_tools_call(
    ctx: &AppContext,
    headers: &axum::http::HeaderMap,
    id: Value,
    params: Value,
) -> Response {
    let name = params
        .get("name")
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_string();
    if name.is_empty() {
        return rpc_http(error_response(
            id,
            INVALID_PARAMS,
            "tools/call requires a tool name",
        ));
    }
    let arguments = params.get("arguments").cloned().unwrap_or(json!({}));

    // make_auth works with or without a session: it is the bridge that
    // produces a session. Every other tool requires a live session.
    if name == TOOL_MAKE_AUTH {
        return make_auth(ctx, headers, id).await;
    }

    let Some(session) = auth_session(ctx, headers).await else {
        return rpc_http(error_response(
            id,
            INTERNAL_ERROR,
            "invalid bearer token: call the make_auth tool to get the authorization link",
        ));
    };
    let user = match users::Entity::find_by_id(session.owner_id)
        .one(&ctx.db)
        .await
    {
        Ok(Some(u)) => u,
        _ => {
            return rpc_http(error_response(
                id,
                INTERNAL_ERROR,
                "session owner not found",
            ))
        }
    };

    match name.as_str() {
        TOOL_SEARCH => tool_search(ctx, id, session.id, &arguments).await,
        TOOL_ADD => tool_add(ctx, id, session.id, &user.email, &arguments).await,
        _ => call_granted_tool(ctx, id, session.id, user.id, user.email, &name, arguments).await,
    }
}

/// `make_auth` builtin handler: returns the mcpsec UI link where the human
/// logs in and creates the proxy session (the bearer token). When the caller
/// already sent a valid session token, the link doubles as a confirmation
/// that authentication is working.
async fn make_auth(ctx: &AppContext, headers: &axum::http::HeaderMap, id: Value) -> Response {
    let authenticated = auth_session(ctx, headers).await.is_some();
    let ui_url = ui_base_url();
    let auth_url = format!("{ui_url}/proxy");
    let text = if authenticated {
        format!(
            "This proxy session is already valid. To manage sessions or create \
             another one, open {auth_url} in a browser, log in and use \
             \"Criar sessão\" — the token shown there is the bearer token for this MCP."
        )
    } else {
        format!(
            "Authorization required. Ask the human to open {auth_url} in a \
             browser, log in, click \"Criar sessão\" and copy the displayed \
             token. Then use it as the Authorization: Bearer header on this MCP \
             endpoint and re-initialize."
        )
    };
    let content = json!({
        "content": [{ "type": "text", "text": text }],
        "structuredContent": {
            "authenticated": authenticated,
            "auth_url": auth_url,
            "ui_url": ui_url,
            "instructions": "open auth_url, log in, create a proxy session, \
                             use the shown token as the bearer token",
        },
        "isError": false,
    });
    rpc_http(ok_response(id, content))
}

/// Base URL of the mcpsec UI for links handed to agents.
///
/// Resolution order: `APP_BASE_URL` env override, else the request host when
/// present, else `http://localhost:5150` (the Loco default port). Only scheme
/// + host — path components would break the link's target.
fn ui_base_url() -> String {
    if let Ok(base) = std::env::var("APP_BASE_URL") {
        let base = base.trim_end_matches('/').to_string();
        if !base.is_empty() {
            return base;
        }
    }
    format!(
        "http://localhost:{}",
        std::env::var("PORT").unwrap_or_else(|_| "5150".to_string())
    )
}

/// `tool_search` builtin: callable tools of this session + catalog.
async fn tool_search(ctx: &AppContext, id: Value, session_id: i64, args: &Value) -> Response {
    let query = args
        .get("query")
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_lowercase();

    let servers = match mcp_servers::Model::list_active(&ctx.db).await {
        Ok(s) => s,
        Err(e) => return rpc_http(error_response(id, INTERNAL_ERROR, &e.to_string())),
    };

    // Catalog: every authorized server with a one-line description and its
    // tool count — the "there are N tools from ClickUp" blurb.
    let mut catalog: Vec<Value> = Vec::new();
    for server in &servers {
        let tool_count = mcp_tools::Model::list_for_server(&ctx.db, server.id)
            .await
            .map(|t| t.len())
            .unwrap_or(0);
        let summary = format!(
            "{} — {} ({} tools{})",
            server.title,
            server
                .description
                .clone()
                .unwrap_or_else(|| server.registry_name.clone()),
            tool_count,
            if tool_count > 0 {
                ""
            } else {
                ", discovery pending"
            },
        );
        let hay = format!(
            "{} {} {}",
            server.registry_name,
            server.title,
            server.description.clone().unwrap_or_default()
        )
        .to_lowercase();
        if query.is_empty() || hay.contains(&query) {
            catalog.push(json!({
                "server": server.registry_name,
                "title": server.title,
                "summary": summary,
                "tool_count": tool_count,
                "how_to_load": format!("call tool_add with server=\"{}\"", server.registry_name),
            }));
        }
    }

    // Tools already granted to this session (callable right now).
    let granted = mcp_proxy_grants::ActiveModel::live_for_session(&ctx.db, session_id)
        .await
        .unwrap_or_default();
    let mut callable: Vec<Value> = Vec::new();
    for (grant, tool) in &granted {
        let server_name = mcp_servers::Entity::find_by_id(tool.mcp_server_id)
            .one(&ctx.db)
            .await
            .ok()
            .flatten()
            .map(|s| s.registry_name)
            .unwrap_or_else(|| format!("server-{}", tool.mcp_server_id));
        let hay = format!("{server_name} {} {}", tool.tool_name, tool.category).to_lowercase();
        if query.is_empty() || hay.contains(&query) {
            callable.push(json!({
                "tool": tool.tool_name,
                "server": server_name,
                "category": tool.category,
                "expires_at": grant.expires_at.to_rfc3339(),
                "status": "callable now",
            }));
        }
    }

    let content = json!({
        "content": [{
            "type": "text",
            "text": format!(
                "{} tool(s) callable now; {} authorized server(s) in catalog.",
                callable.len(),
                catalog.len()
            ),
        }],
        "structuredContent": {
            "callable_tools": callable,
            "catalog": catalog,
        },
        "isError": false,
    });
    rpc_http(ok_response(id, content))
}

/// `tool_add` builtin: resolve a server, grant its (optionally filtered)
/// tools with TTL, and return what became callable.
async fn tool_add(
    ctx: &AppContext,
    id: Value,
    session_id: i64,
    user_email: &str,
    args: &Value,
) -> Response {
    let server_query = args
        .get("server")
        .and_then(Value::as_str)
        .unwrap_or("")
        .trim()
        .to_string();
    if server_query.is_empty() {
        return rpc_http(error_response(
            id,
            INVALID_PARAMS,
            "tool_add requires `server` (name from tool_search)",
        ));
    }
    let query = args
        .get("query")
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_lowercase();
    let ttl = args
        .get("ttl_seconds")
        .and_then(Value::as_i64)
        .unwrap_or(DEFAULT_TOOL_TTL_SECONDS)
        .clamp(30, MAX_TOOL_TTL_SECONDS);

    let servers = match mcp_servers::Model::list_active(&ctx.db).await {
        Ok(s) => s,
        Err(e) => return rpc_http(error_response(id, INTERNAL_ERROR, &e.to_string())),
    };
    let q = server_query.to_lowercase();
    let matches: Vec<_> = servers
        .iter()
        .filter(|s| {
            s.registry_name.to_lowercase().contains(&q) || s.title.to_lowercase().contains(&q)
        })
        .collect();
    if matches.is_empty() {
        return rpc_http(error_response(
            id,
            INVALID_PARAMS,
            &format!("no authorized server matches \"{server_query}\""),
        ));
    }
    if matches.len() > 1 {
        let names: Vec<&str> = matches.iter().map(|s| s.registry_name.as_str()).collect();
        return rpc_http(error_response(
            id,
            INVALID_PARAMS,
            &format!(
                "ambiguous server \"{}\"; be specific: {}",
                server_query,
                names.join(", ")
            ),
        ));
    }
    let server = matches[0];

    let tools = match mcp_tools::Model::list_for_server(&ctx.db, server.id).await {
        Ok(t) => t,
        Err(e) => return rpc_http(error_response(id, INTERNAL_ERROR, &e.to_string())),
    };
    let selected: Vec<_> = tools
        .iter()
        .filter(|t| {
            query.is_empty()
                || t.tool_name.to_lowercase().contains(&query)
                || t.description
                    .as_deref()
                    .unwrap_or("")
                    .to_lowercase()
                    .contains(&query)
        })
        .collect();
    if selected.is_empty() {
        return rpc_http(error_response(
            id,
            INVALID_PARAMS,
            &format!("no tools of {} match \"{}\"", server.registry_name, query),
        ));
    }

    let expires = chrono::Utc::now() + chrono::Duration::seconds(ttl);
    let mut added = Vec::with_capacity(selected.len());
    for tool in &selected {
        let expires_at: chrono::DateTime<chrono::FixedOffset> = expires.into();
        if let Ok(grant) = mcp_proxy_grants::ActiveModel::grant(
            &ctx.db,
            session_id,
            tool.id,
            expires_at,
            Some(user_email),
        )
        .await
        {
            added.push(json!({
                "tool": tool.tool_name,
                "category": tool.category,
                "description": tool.description,
                "expires_at": grant.expires_at.to_rfc3339(),
                "how_to_call": format!(
                    "tools/call with name=\"{}\" and arguments matching its inputSchema",
                    tool.tool_name
                ),
            }));
        }
    }

    let content = json!({
        "content": [{
            "type": "text",
            "text": format!(
                "Loaded {} tool(s) from {} until {}.",
                added.len(),
                server.registry_name,
                expires.to_rfc3339()
            ),
        }],
        "structuredContent": { "added": added, "ttl_seconds": ttl },
        "isError": false,
    });
    rpc_http(ok_response(id, content))
}

/// Execute a granted tool, enforcing the category guard (WRITE/ADMIN need
/// `confirmed: true`) and writing the same audit trail as the runner.
async fn call_granted_tool(
    ctx: &AppContext,
    id: Value,
    session_id: i64,
    user_id: i64,
    _user_email: String,
    tool_name: &str,
    arguments: Value,
) -> Response {
    // The tool must be granted to this session right now.
    let granted = mcp_proxy_grants::ActiveModel::live_for_session(&ctx.db, session_id)
        .await
        .unwrap_or_default();
    let Some((_grant, tool)) = granted.iter().find(|(_, t)| t.tool_name == tool_name) else {
        return rpc_http(error_response(
            id,
            METHOD_NOT_FOUND,
            &format!(
                "tool \"{tool_name}\" is not loaded in this session; call tool_search / tool_add first"
            ),
        ));
    };
    let tool = tool.clone();

    let confirmed = arguments
        .get("confirmed")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let category = mcp_proxy_grants::grant_category(&tool);
    if category != mcp_servers::ToolCategory::ReadOnly && !confirmed {
        return rpc_http(error_response(
            id,
            INVALID_PARAMS,
            &format!(
                "tool \"{}\" is {} and requires {{\"confirmed\": true}} among the arguments",
                tool.tool_name,
                category.as_str()
            ),
        ));
    }

    let Some(server) = mcp_servers::Entity::find_by_id(tool.mcp_server_id)
        .one(&ctx.db)
        .await
        .ok()
        .flatten()
    else {
        return rpc_http(error_response(id, INTERNAL_ERROR, "server not found"));
    };

    let started = std::time::Instant::now();
    let client = match crate::workers::mcp::McpClient::new(
        &server.remote_url,
        std::time::Duration::from_secs(60),
    ) {
        Ok(c) => c,
        Err(e) => return rpc_http(error_response(id, INTERNAL_ERROR, &e)),
    };
    let outcome = match client.initialize().await {
        Ok(_) => client.call_tool(&tool.tool_name, arguments.clone()).await,
        Err(e) => Err(e),
    };

    let duration_ms = i64::try_from(started.elapsed().as_millis()).unwrap_or(i64::MAX);
    let (status, result_json, error): (&str, Option<Value>, Option<String>) = match &outcome {
        Ok(v) => ("success", Some(v.clone()), None),
        Err(e) => ("error", None, Some(e.clone())),
    };

    // Audit row: same trail as the runner (persist failure is logged, not fatal).
    let audit = tool_calls::ActiveModel {
        mcp_server_id: Set(server.id),
        mcp_tool_id: Set(tool.id),
        user_id: Set(user_id),
        tool_name: Set(tool.tool_name.clone()),
        arguments: Set(Some(arguments)),
        result: Set(result_json),
        status: Set(status.to_string()),
        category: Set(category.as_str().to_string()),
        confirmed: Set(confirmed),
        error: Set(error),
        duration_ms: Set(duration_ms),
        ..Default::default()
    };
    if let Err(e) = audit.insert(&ctx.db).await {
        tracing::error!(error = %e, "could not persist proxy tool call audit row");
    }

    match outcome {
        Ok(value) => rpc_http(ok_response(
            id,
            json!({
                "content": [{
                    "type": "text",
                    "text": serde_json::to_string_pretty(&value).unwrap_or_default(),
                }],
                "structuredContent": value,
                "isError": false,
            }),
        )),
        Err(err) => rpc_http(ok_response(
            id,
            json!({
                "content": [{"type": "text", "text": format!("tool execution failed: {err}")}],
                "isError": true,
            }),
        )),
    }
}

// ------------------------------------------------------------------ plumbing

fn bearer(headers: &axum::http::HeaderMap) -> Option<String> {
    headers
        .get("authorization")
        .and_then(|v| v.to_str().ok())
        .and_then(|v| v.strip_prefix("Bearer "))
        .map(str::to_string)
}

async fn auth_session(
    ctx: &AppContext,
    headers: &axum::http::HeaderMap,
) -> Option<mcp_proxy_sessions::Model> {
    let token = bearer(headers)?;
    mcp_proxy_sessions::Entity::find_live_by_token(&ctx.db, &token)
        .await
        .ok()
        .flatten()
}

fn ok_response(id: Value, result: Value) -> Value {
    json!({"jsonrpc": "2.0", "id": id, "result": result})
}

fn error_response(id: Value, code: i64, message: &str) -> Value {
    json!({"jsonrpc": "2.0", "id": id, "error": {"code": code, "message": message}})
}

/// Serialize a JSON-RPC message as an HTTP response (JSON content type).
fn rpc_http(body: Value) -> Response {
    (
        StatusCode::OK,
        [(axum::http::header::CONTENT_TYPE, "application/json")],
        serde_json::to_string(&body).unwrap_or_default(),
    )
        .into_response()
}

