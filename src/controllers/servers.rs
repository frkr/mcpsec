use loco_rs::prelude::*;
use serde::Deserialize;
use ts_rs::TS;

use crate::models::{mcp_servers, mcp_tools};
use crate::views::servers::{ServerDetail, ServerSummary, ToolView};

#[derive(Debug, Deserialize, Default)]
pub struct ListParams {
    /// Free-text filter over registry name, title and description.
    pub q: Option<String>,
    /// Lifecycle filter (`new`, `active`, …).
    pub lifecycle: Option<String>,
    /// Source filter: `registry` (mirrored rows only), `custom` (hand-added)
    /// or `all`/omitted for both.
    pub sync_source: Option<String>,
    /// 1-based page number (default 1).
    pub page: Option<u64>,
    /// Rows per page (default 50, max 200).
    pub page_size: Option<u64>,
}

/// `GET /api/servers` — paginated registry snapshot with optional filters.
///
/// The registry holds tens of thousands of servers, so the listing is always
/// paged and filtered in SQL; the client never downloads the whole table.
#[debug_handler]
pub async fn list(
    _auth: auth::JWT,
    State(ctx): State<AppContext>,
    Query(params): Query<ListParams>,
) -> Result<Response> {
    let page = mcp_servers::Model::paginate_with_source(
        &ctx.db,
        params.q.as_deref(),
        params.lifecycle.as_deref(),
        params.sync_source.as_deref(),
        params.page.unwrap_or(1),
        params.page_size.unwrap_or(50),
    )
    .await?;
    let items: Vec<ServerSummary> = page.items.iter().map(ServerSummary::from_model).collect();
    format::json(serde_json::json!({
        "servers": items,
        "page": page.page,
        "page_size": page.page_size,
        "total_items": page.total_items,
        "filtered_items": page.filtered_items,
        "total_pages": page.total_pages,
        "counts": page.counts,
    }))
}

/// `GET /api/servers/{id}` — one server with its tools.
#[debug_handler]
pub async fn detail(
    _auth: auth::JWT,
    State(ctx): State<AppContext>,
    Path(id): Path<i64>,
) -> Result<Response> {
    let Some(server) = mcp_servers::Entity::find_by_id(id).one(&ctx.db).await? else {
        return not_found();
    };
    let tools = mcp_tools::Model::list_for_server(&ctx.db, id).await?;
    let detail = ServerDetail::from_models(&server, &tools);
    format::json(detail)
}

#[derive(Debug, Deserialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct LabelInput {
    #[ts(type = "number")]
    pub tool_id: i64,
    pub category: String,
}

/// `POST /api/servers/{id}/activate` — enter the activation workflow. The
/// worker discovers and labels tools in the background; the UI polls
/// `GET /api/servers/{id}` until lifecycle becomes `awaiting_review`.
#[debug_handler]
pub async fn activate(
    _auth: auth::JWT,
    State(ctx): State<AppContext>,
    Path(id): Path<i64>,
) -> Result<Response> {
    let Some(server) = mcp_servers::Entity::find_by_id(id).one(&ctx.db).await? else {
        return not_found();
    };
    let am: mcp_servers::ActiveModel = server.into();
    let _ = am.start_activation(&ctx.db).await?;
    crate::workers::activation::ActivationWorker::perform_later(
        &ctx,
        crate::workers::activation::ActivationWorkerArgs { server_id: id },
    )
    .await?;
    format::json(serde_json::json!({ "ok": true, "status": "activating" }))
}

/// `POST /api/servers/{id}/approve` — finish the workflow: server goes active
/// and runnable. Optionally applies final tool labels in the same request.
#[debug_handler]
pub async fn approve(
    auth: auth::JWT,
    State(ctx): State<AppContext>,
    Path(id): Path<i64>,
    Json(params): Json<ApproveParams>,
) -> Result<Response> {
    let user = load_user(&ctx, &auth).await?;
    let Some(server) = mcp_servers::Entity::find_by_id(id).one(&ctx.db).await? else {
        return not_found();
    };

    if let Some(labels) = &params.labels {
        for label in labels {
            let category = mcp_servers::ToolCategory::parse(&label.category);
            // Ownership check: a label for a tool of another server is a
            // client bug, not a server fault — 400 with the id, never a 500.
            if let Err(e) = mcp_tools::ActiveModel::set_category_for_server(
                &ctx.db,
                id,
                label.tool_id,
                category,
            )
            .await
            {
                return match e {
                    mcp_tools::SetCategoryError::NotFound => bad_request(format!(
                        "tool {} does not belong to server {} (or does not exist)",
                        label.tool_id, id
                    )),
                    mcp_tools::SetCategoryError::Db(err) => return Err(err.into()),
                };
            }
        }
    }

    let am: mcp_servers::ActiveModel = server.into();
    let saved = am.approve(&ctx.db, &user).await?;
    let tools = mcp_tools::Model::list_for_server(&ctx.db, id).await?;
    format::json(ServerDetail::from_models(&saved, &tools))
}

#[derive(Debug, Deserialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct ApproveParams {
    pub labels: Option<Vec<LabelInput>>,
}

