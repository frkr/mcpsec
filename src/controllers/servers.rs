/// `POST /api/servers/{id}/tools/{tool_id}/label` — relabel one tool.
#[debug_handler]
pub async fn relabel(
    _auth: auth::JWT,
    State(ctx): State<AppContext>,
    Path((id, tool_id)): Path<(i64, i64)>,
    Json(params): Json<RelabelParams>,
) -> Result<Response> {
    let _ = id; // tool ids are globally unique; path keeps URLs self-describing
    let category = mcp_servers::ToolCategory::parse(&params.category);
    let tool = mcp_tools::ActiveModel::set_category(&ctx.db, tool_id, category).await?;
    format::json(ToolView::from_model(&tool))
}

#[derive(Debug, Deserialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct RelabelParams {
    pub category: String,
}

/// `POST /api/servers/{id}/meta` — set the user's display title/description.
/// Empty strings clear the override (registry values shine through).
#[derive(Debug, Deserialize, TS)]
#[ts(export, export_to = "../frontend/src/bindings/")]
pub struct ServerMetaParams {
    pub title: Option<String>,
    pub description: Option<String>,
}

#[debug_handler]
pub async fn update_meta(
    _auth: auth::JWT,
    State(ctx): State<AppContext>,
    Path(id): Path<i64>,
    Json(params): Json<ServerMetaParams>,
) -> Result<Response> {
    let server = mcp_servers::Entity::find_by_id(id)
        .one(&ctx.db)
        .await?
        .ok_or(loco_rs::Error::NotFound)?;
    let saved = server
        .set_custom_meta(&ctx.db, params.title, params.description)
        .await?;
    let tools = mcp_tools::Model::list_for_server(&ctx.db, saved.id).await?;
    format::json(ServerDetail::from_models(&saved, &tools))
}

/// `POST /api/servers/acknowledge-new` — bulk-acknowledge every `new` server
/// so the NOVO badge stops nagging (settings screen action).
#[debug_handler]
pub async fn acknowledge_new(_auth: auth::JWT, State(ctx): State<AppContext>) -> Result<Response> {
    let updated = mcp_servers::Model::acknowledge_all_new(&ctx.db).await?;
    format::json(serde_json::json!({ "ok": true, "acknowledged": updated }))
}

/// `GET /api/servers/authorized` — servers cleared to run, with tools, for
/// the runner screen.
#[debug_handler]
pub async fn authorized(_auth: auth::JWT, State(ctx): State<AppContext>) -> Result<Response> {
    let servers = mcp_servers::Model::list_active(&ctx.db).await?;
    let mut items = Vec::with_capacity(servers.len());
    for server in &servers {
        let tools = mcp_tools::Model::list_for_server(&ctx.db, server.id).await?;
        items.push(ServerDetail::from_models(server, &tools));
    }
    format::json(serde_json::json!({ "servers": items }))
}

async fn load_user(ctx: &AppContext, auth: &auth::JWT) -> Result<String> {
    let user = crate::models::users::Model::find_by_pid(&ctx.db, &auth.claims.pid).await?;
    Ok(user.email)
}

pub fn routes() -> Routes {
    Routes::new()
        .prefix("/api/servers")
        .add("/", get(list))
        .add("/authorized", get(authorized))
        .add("/{id}", get(detail))
        .add("/{id}/activate", post(activate))
        .add("/{id}/approve", post(approve))
        .add("/{id}/reject", post(reject))
        .add("/{id}/disable", post(disable))
        .add("/{id}/tools/{tool_id}/label", post(relabel))
        // PUT is the intended verb (idempotent partial update) and is what the
        // SPA sends; POST stays for compatibility with existing clients.
        .add("/{id}/meta", put(update_meta))
        .add("/{id}/meta", post(update_meta))
        .add("/acknowledge-new", post(acknowledge_new))
}
