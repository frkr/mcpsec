//! Proxy MCP endpoint tests: the make_auth onboarding bridge and the
//! session-gated surface.

use loco_rs::testing::prelude::*;
use mcpsec::app::App;
use serde_json::Value;

use super::prepare_data;

/// POST one JSON-RPC message to /mcp with optional Authorization header.
async fn rpc(request: &loco_rs::TestServer, token: Option<&str>, body: Value) -> Value {
    let mut req = request
        .post("/mcp")
        .add_header("content-type", "application/json");
    if let Some(t) = token {
        req = req.add_header("authorization", format!("Bearer {t}"));
    }
    let response = req.json(&body).await;
    serde_json::from_str(&response.text()).unwrap_or(Value::Null)
}

#[tokio::test]
#[serial_test::serial]
async fn tools_list_without_token_exposes_only_make_auth() {
    request::<App, _, _>(|request, _ctx| async move {
        let res = rpc(
            &request,
            None,
            serde_json::json!({"jsonrpc":"2.0","id":1,"method":"tools/list","params":{}}),
        )
        .await;
        let tools = res["result"]["tools"].as_array().unwrap();
        assert_eq!(tools.len(), 1, "unauthenticated surface must be minimal");
        assert_eq!(tools[0]["name"], "make_auth");
    })
    .await;
}

#[tokio::test]
#[serial_test::serial]
async fn make_auth_answers_without_a_session() {
    request::<App, _, _>(|request, _ctx| async move {
        let res = rpc(
            &request,
            None,
            serde_json::json!({
                "jsonrpc":"2.0","id":2,"method":"tools/call",
                "params":{"name":"make_auth","arguments":{}}
            }),
        )
        .await;
        assert_eq!(res["result"]["isError"], false);
        let structured = &res["result"]["structuredContent"];
        assert_eq!(structured["authenticated"], false);
        let url = structured["auth_url"].as_str().unwrap();
        assert!(
            url.ends_with("/proxy"),
            "link must point at the proxy UI: {url}"
        );
        assert!(!res["result"]["content"][0]["text"]
            .as_str()
            .unwrap_or_default()
            .is_empty());
    })
    .await;
}

#[tokio::test]
#[serial_test::serial]
async fn make_auth_reports_valid_session() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        // create a proxy session to get a live token
        let created = request
            .post("/api/proxy/sessions")
            .json(&serde_json::json!({}))
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        let token = serde_json::from_str::<Value>(&created.text())
            .ok()
            .and_then(|v| v["token"].as_str().map(str::to_string))
            .unwrap_or_default();
        assert!(!token.is_empty(), "session creation must return a token");

        let res = rpc(
            &request,
            Some(&token),
            serde_json::json!({
                "jsonrpc":"2.0","id":3,"method":"tools/call",
                "params":{"name":"make_auth","arguments":{}}
            }),
        )
        .await;
        assert_eq!(res["result"]["structuredContent"]["authenticated"], true);
    })
    .await;
}

#[tokio::test]
#[serial_test::serial]
async fn make_auth_reports_invalid_token_as_unauthenticated() {
    request::<App, _, _>(|request, _ctx| async move {
        let res = rpc(
            &request,
            Some("not-a-real-token"),
            serde_json::json!({
                "jsonrpc":"2.0","id":4,"method":"tools/call",
                "params":{"name":"make_auth","arguments":{}}
            }),
        )
        .await;
        assert_eq!(res["result"]["structuredContent"]["authenticated"], false);
    })
    .await;
}
