/// Delete is allowed only from `new`, `rejected` and `disabled`.
///
/// `activating` has a discovery worker holding the row, and `awaiting_review`
/// still owes a decision (rejecting it records *who* declined). Both must be
/// refused, and the row must survive.
#[tokio::test]
#[serial]
async fn delete_is_refused_while_activating_or_awaiting_review() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;

        for (name, lifecycle) in [
            ("mid-discovery", "activating"),
            ("still-reviewing", "awaiting_review"),
            ("rejected-one", "rejected"),
            ("disabled-one", "disabled"),
        ] {
            let created = authed(
                &request,
                "POST",
                "/api/custom-servers",
                &logged_in.token,
                Some(json!({
                    "registry_name": name,
                    "title": name,
                    "version": "1.0.0",
                    "remote_url": VALID_URL,
                })),
            )
            .await;
            assert_eq!(created.status_code(), 200, "{}", created.text());
            let id = created.json()["id"].as_i64().unwrap();

            let saved = mcp_servers::Entity::find_by_id(id)
                .one(&ctx.db)
                .await
                .unwrap()
                .unwrap();
            let mut am: mcp_servers::ActiveModel = saved.into();
            am.lifecycle = sea_orm::Set(lifecycle.to_string());
            am.update(&ctx.db).await.unwrap();

            let deleted = authed(
                &request,
                "DELETE",
                &format!("/api/custom-servers/{id}"),
                &logged_in.token,
                None,
            )
            .await;

            // The two mid-workflow states are refused; the two settled states
            // are deletable — the allowlist, both directions.
            let deletable = matches!(lifecycle, "rejected" | "disabled");
            if deletable {
                assert_eq!(
                    deleted.status_code(),
                    200,
                    "{lifecycle}: {}",
                    deleted.text()
                );
            } else {
                assert_eq!(
                    deleted.status_code(),
                    409,
                    "{lifecycle}: {}",
                    deleted.text()
                );
                assert!(
                    mcp_servers::Entity::find_by_id(id)
                        .one(&ctx.db)
                        .await
                        .unwrap()
                        .is_some(),
                    "{lifecycle}: a refused delete must leave the row in place"
                );
            }
        }
    })
    .await;
}
