/// Deleting an `active` server is refused: proxy sessions may be holding it.
#[tokio::test]
#[serial]
async fn delete_active_custom_server_is_refused() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let created = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(json!({
                "registry_name": "active-one",
                "title": "Active",
                "version": "1.0.0",
                "remote_url": VALID_URL,
            })),
        )
        .await;
        let id = created.json()["id"].as_i64().unwrap();

        let saved = mcp_servers::Entity::find_by_id(id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        let am: mcp_servers::ActiveModel = saved.into();
        am.approve(&ctx.db, &logged_in.user.email).await.unwrap();

        let deleted = authed(
            &request,
            "DELETE",
            &format!("/api/custom-servers/{id}"),
            &logged_in.token,
            None,
        )
        .await;
        assert_eq!(deleted.status_code(), 409, "{}", deleted.text());
        // "disable it first" is the actionable part; make sure it ships.
        assert!(
            deleted.json()["description"]
                .as_str()
                .is_some_and(|d| d.contains("disable")),
            "the refusal must say what to do instead, got: {}",
            deleted.text()
        );
        assert!(
            mcp_servers::Entity::find_by_id(id)
                .one(&ctx.db)
                .await
                .unwrap()
                .is_some(),
            "an active server must survive the refused delete"
        );
    })
    .await;
}

/// Activating a custom server enters the shared workflow: the row flips to
/// `activating` before the worker (which will fail to dial the fake endpoint)
/// takes over.
#[tokio::test]
#[serial]
async fn can_activate_custom_server() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let created = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(json!({
                "registry_name": "activatable",
                "title": "Activatable",
                "version": "1.0.0",
                "remote_url": VALID_URL,
            })),
        )
        .await;
        let id = created.json()["id"].as_i64().unwrap();

        let activated = authed(
            &request,
            "POST",
            &format!("/api/custom-servers/{id}/activate"),
            &logged_in.token,
            Some(json!({})),
        )
        .await;
        assert_eq!(activated.status_code(), 200, "{}", activated.text());
        let body: Value = serde_json::from_str(activated.text()).unwrap();
        assert_eq!(body["status"], "activating");

        let saved = mcp_servers::Entity::find_by_id(id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        // The test config runs workers in `ForegroundBlocking` mode, so the
        // discovery attempt already ran and failed against the fake host,
        // parking the row back in `new` with the error recorded. Either state
        // proves the shared workflow was entered.
        assert!(
            saved.lifecycle == "activating" || saved.lifecycle == "new",
            "activation must move the row into the shared workflow, got {}",
            saved.lifecycle
        );
        assert_eq!(
            saved.sync_source, "custom",
            "the workflow must not rewrite the source"
        );
    })
    .await;
}

