//! Custom ("manually registered") MCP server CRUD.
//!
//! These tests exercise the whole HTTP path — auth guard, validation, the
//! `sync_source` stamp and the lifecycle hand-off — because the two things
//! most likely to break here are exactly the ones a model test cannot see: a
//! route that was never registered (404) and a guard that answers with the
//! wrong status (500 instead of 400/409).

use loco_rs::testing::prelude::*;
use mcpsec::app::App;
use mcpsec::models::mcp_servers;
use sea_orm::{ActiveModelTrait, EntityTrait};
use serde_json::{json, Value};
use serial_test::serial;

use super::prepare_data;

const VALID_URL: &str = "https://mcp.clickup.com/mcp";

/// POST/PUT/DELETE with the logged-in user's bearer token.
async fn authed(
    request: &loco_rs::TestServer,
    method: &str,
    path: &str,
    token: &str,
    body: Option<Value>,
) -> Reply {
    let req = match method {
        "POST" => request.post(path),
        "PUT" => request.put(path),
        "DELETE" => request.delete(path),
        other => panic!("unsupported method {other}"),
    }
    .add_header("authorization", format!("Bearer {token}"));
    let response = match body {
        Some(body) => req.json(&body).await,
        None => req.await,
    };
    Reply {
        status: response.status_code(),
        text: response.text(),
    }
}

/// The two things these tests read off a response, captured so the helper can
/// return a plain struct instead of depending on the test server's response
/// type (which `loco_rs` does not re-export).
struct Reply {
    status: axum::http::StatusCode,
    text: String,
}

impl Reply {
    fn status_code(&self) -> axum::http::StatusCode {
        self.status
    }

    fn text(&self) -> &str {
        &self.text
    }

    fn json(&self) -> Value {
        serde_json::from_str(&self.text).expect("response must be JSON")
    }
}

/// `POST /api/custom-servers` stamps `sync_source = custom`, starts in `new`
/// and is invisible to the registry-only listing.
#[tokio::test]
#[serial]
async fn can_create_custom_server() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;

        let response = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(json!({
                "registry_name": "clickup",
                "title": "ClickUp",
                "description": "ClickUp MCP server",
                "version": "1.0.0",
                "remote_url": VALID_URL,
            })),
        )
        .await;
        assert_eq!(response.status_code(), 200, "{}", response.text());

        let body: Value = serde_json::from_str(response.text()).unwrap();
        assert_eq!(body["registry_name"], "clickup");
        assert_eq!(body["sync_source"], "custom");
        // Custom rows start DISABLED and pre-acknowledged: no NOVO badge, no
        // bulk-triage count; activation runs the same discovery workflow.
        assert_eq!(body["lifecycle"], "disabled");
        assert_eq!(body["enabled"], false);
        assert_eq!(body["remote_url"], VALID_URL);
        assert_eq!(
            body["remote_type"], "streamable-http",
            "the transport must default to the one the MCP client speaks"
        );

        // The row really is in the table with the custom stamp.
        let saved = mcp_servers::Model::find_by_registry_name(&ctx.db, "clickup")
            .await
            .unwrap()
            .expect("the custom server should be persisted");
        assert_eq!(saved.sync_source, "custom");
        // Custom rows are born disabled AND pre-acknowledged (no NOVO badge).
        assert_eq!(saved.lifecycle, "disabled");
        assert!(!saved.enabled, "a new custom server starts disabled");
        assert!(
            saved.acknowledged_at.is_some(),
            "custom rows must not surface in triage"
        );

        // The registry listing must not show it: it is a different source.
        let registry = request
            .get("/api/servers?sync_source=registry")
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        let registry_body: Value = serde_json::from_str(&registry.text()).unwrap();
        assert_eq!(
            registry_body["total_items"], 0,
            "custom rows must stay out of the registry-only listing"
        );
    })
    .await;
}

/// A duplicate `registry_name` is a 409, not a 500 from the unique index.
#[tokio::test]
#[serial]
async fn create_rejects_duplicate_registry_name() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let payload = json!({
            "registry_name": "dup",
            "title": "Dup",
            "version": "1.0.0",
            "remote_url": VALID_URL,
        });

        let first = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(payload.clone()),
        )
        .await;
        assert_eq!(first.status_code(), 200, "{}", first.text());

        let second = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(payload),
        )
        .await;
        assert_eq!(second.status_code(), 409, "{}", second.text());
        // The body must explain itself: the SPA turns `description` into the
        // message it shows, so a bare status would leave the user guessing.
        let body: Value = second.json();
        assert_eq!(body["error"], "conflict");
        assert!(
            body["description"]
                .as_str()
                .is_some_and(|d| d.contains("already exists")),
            "the 409 must carry a readable reason, got: {}",
            second.text()
        );
    })
    .await;
}

/// `http://` is refused before the row is written: the activation worker would
/// reject it later anyway, and a saved row that can never activate is a trap.
#[tokio::test]
#[serial]
async fn create_rejects_non_https_remote_url() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;

        let response = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(json!({
                "registry_name": "insecure",
                "title": "Insecure",
                "version": "1.0.0",
                "remote_url": "http://mcp.example.com/mcp",
            })),
        )
        .await;
        assert_eq!(response.status_code(), 400, "{}", response.text());
        assert!(
            mcp_servers::Model::find_by_registry_name(&ctx.db, "insecure")
                .await
                .unwrap()
                .is_none(),
            "a rejected URL must not leave a row behind"
        );

        // The SSRF fence also catches https onto a private host.
        let local = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(json!({
                "registry_name": "local",
                "title": "Local",
                "version": "1.0.0",
                "remote_url": "https://localhost:8443/mcp",
            })),
        )
        .await;
        assert_eq!(local.status_code(), 400, "{}", local.text());
    })
    .await;
}

/// PUT edits title/description/endpoint, and refuses an unsafe URL.
#[tokio::test]
#[serial]
async fn can_update_custom_server() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let created = authed(
            &request,
            "POST",
            "/api/custom-servers",
            &logged_in.token,
            Some(json!({
                "registry_name": "updatable",
                "title": "Before",
                "version": "1.0.0",
                "remote_url": VALID_URL,
            })),
        )
        .await;
        let id = created.json()["id"].as_i64().unwrap();

        let updated = authed(
            &request,
            "PUT",
            &format!("/api/custom-servers/{id}"),
            &logged_in.token,
            Some(json!({
                "title": "After",
                "description": "novo texto",
                "remote_url": "https://mcp.example.com/v2",
            })),
        )
        .await;
        assert_eq!(updated.status_code(), 200, "{}", updated.text());
        let body: Value = serde_json::from_str(updated.text()).unwrap();
        assert_eq!(body["title"], "After");
        assert_eq!(body["description"], "novo texto");
        assert_eq!(body["remote_url"], "https://mcp.example.com/v2");
        assert_eq!(
            body["version"], "1.0.0",
            "untouched fields keep their value"
        );

        let bad = authed(
            &request,
            "PUT",
            &format!("/api/custom-servers/{id}"),
            &logged_in.token,
            Some(json!({ "remote_url": "http://plain.example.com/mcp" })),
        )
        .await;
        assert_eq!(bad.status_code(), 400, "{}", bad.text());

        // The refused update must not have been half-applied.
        let saved = mcp_servers::Entity::find_by_id(id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(saved.remote_url, "https://mcp.example.com/v2");
    })
    .await;
}

