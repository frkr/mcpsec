//! The review endpoints are the human gate of the activation workflow. These
//! tests drive the real HTTP path the Review screen uses — approve with
//! labels, reject, disable, and the new "pause review" action — so a model
//! regression (wrong state transition, lost audit field) shows up as a 4xx/5xx
//! here instead of a broken button in production.

use loco_rs::testing::prelude::*;
use mcpsec::app::App;
use mcpsec::models::_entities::mcp_tools as tools_ent;
use mcpsec::models::{mcp_servers, mcp_tools};
use sea_orm::{ActiveModelTrait, ColumnTrait, EntityTrait, QueryFilter, Set};
use serde_json::{json, Value};

use super::prepare_data;

/// Put a server in `awaiting_review` with two discovered tools, so approve
/// has something real to work on.
async fn seed_review_server(
    ctx: &loco_rs::app::AppContext,
    registry_name: &str,
) -> mcp_servers::Model {
    let am = mcp_servers::ActiveModel {
        registry_name: Set(registry_name.to_string()),
        title: Set("Review Target".to_string()),
        description: Set(None),
        version: Set("1.0.0".to_string()),
        remote_url: Set("https://review.example/mcp".to_string()),
        remote_type: Set("streamable-http".to_string()),
        registry_status: Set("active".to_string()),
        is_latest: Set(Some(true)),
        sync_source: Set(mcp_servers::SyncSource::Registry.as_str().to_string()),
        acknowledged_at: Set(None),
        lifecycle: Set(mcp_servers::Lifecycle::AwaitingReview.as_str().to_string()),
        enabled: Set(false),
        last_error: Set(None),
        ..Default::default()
    };
    use sea_orm::ActiveModelTrait;
    let server = am.insert(&ctx.db).await.unwrap();
    for (name, category) in [("read_thing", "READ_ONLY"), ("write_thing", "WRITE")] {
        let tool = mcp_tools::ActiveModel {
            mcp_server_id: Set(server.id),
            tool_name: Set(name.to_string()),
            description: Set(None),
            input_schema: Set(None),
            category: Set(category.to_string()),
            classified_by: Set("heuristic".to_string()),
            enabled: Set(true),
            ..Default::default()
        };
        tool.insert(&ctx.db).await.unwrap();
    }
    server
}

#[tokio::test]
#[serial_test::serial]
async fn approve_activates_the_server() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let server = seed_review_server(&ctx, "approve-target").await;

        let response = request
            .post(format!("/api/servers/{}/approve", server.id).as_str())
            .json(&json!({}))
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        assert_eq!(response.status_code(), 200, "{}", response.text());

        let body: Value = serde_json::from_str(&response.text()).unwrap();
        assert_eq!(body["lifecycle"], "active");
        assert_eq!(body["enabled"], true);

        let reloaded = mcp_servers::Entity::find_by_id(server.id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(reloaded.lifecycle, "active");
        assert_eq!(
            reloaded.activated_by.as_deref(),
            Some(logged_in.user.email.as_str())
        );
    })
    .await;
}

#[tokio::test]
#[serial_test::serial]
async fn approve_with_labels_reclassifies_and_activates() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let server = seed_review_server(&ctx, "approve-labels").await;
        let tools = mcp_tools::Entity::find()
            .filter(tools_ent::Column::McpServerId.eq(server.id))
            .all(&ctx.db)
            .await
            .unwrap();

        let labels: Vec<Value> = tools
            .iter()
            .map(|t| json!({"tool_id": t.id, "category": "ADMIN"}))
            .collect();
        let response = request
            .post(format!("/api/servers/{}/approve", server.id).as_str())
            .json(&json!({ "labels": labels }))
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        assert_eq!(response.status_code(), 200, "{}", response.text());

        let body: Value = serde_json::from_str(&response.text()).unwrap();
        assert_eq!(body["lifecycle"], "active");
        for tool in body["tools"].as_array().unwrap() {
            assert_eq!(tool["category"], "ADMIN");
            // Human relabel: classified_by must flip to user.
            assert_eq!(tool["classified_by"], "user");
        }
    })
    .await;
}

/// Regression for the 500 on `POST /api/servers/6089/approve`: a label whose
/// `tool_id` exists but belongs to a DIFFERENT server must be a clear 400,
/// never a 500. It also pins the ownership rule — one server's review screen
/// must not be able to write another server's tool categories.
#[tokio::test]
#[serial_test::serial]
async fn approve_with_foreign_tool_id_is_a_clear_400() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        let server = seed_review_server(&ctx, "approve-owner").await;
        let other = seed_review_server(&ctx, "approve-other").await;
        let foreign = mcp_tools::Entity::find()
            .filter(tools_ent::Column::McpServerId.eq(other.id))
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();

        let response = request
            .post(format!("/api/servers/{}/approve", server.id).as_str())
            .json(&json!({
                "labels": [{"tool_id": foreign.id, "category": "ADMIN"}]
            }))
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        assert_eq!(response.status_code(), 400, "got: {}", response.text());
        assert!(
            response.text().contains(&foreign.id.to_string()),
            "the error must name the offending tool id"
        );

        // The other server's tool must be untouched.
        let untouched = mcp_tools::Entity::find_by_id(foreign.id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(untouched.classified_by, "heuristic");

        // The approving server must NOT have been activated by a failed review.
        let reloaded = mcp_servers::Entity::find_by_id(server.id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(reloaded.lifecycle, "awaiting_review");
    })
    .await;
}

