#[tokio::test]
#[serial_test::serial]
async fn reject_and_disable_follow_the_same_contract() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;

        let rejected = seed_review_server(&ctx, "reject-target").await;
        let response = request
            .post(format!("/api/servers/{}/reject", rejected.id).as_str())
            .json(&json!({}))
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        assert_eq!(response.status_code(), 200, "{}", response.text());

        let reloaded = mcp_servers::Entity::find_by_id(rejected.id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(reloaded.lifecycle, "rejected");

        // disable from awaiting_review: the "pause review" action (#127).
        let disabled = seed_review_server(&ctx, "disable-target").await;
        let response = request
            .post(format!("/api/servers/{}/disable", disabled.id).as_str())
            .json(&json!({}))
            .add_header("authorization", format!("Bearer {}", logged_in.token))
            .await;
        assert_eq!(response.status_code(), 200, "{}", response.text());

        let reloaded = mcp_servers::Entity::find_by_id(disabled.id)
            .one(&ctx.db)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(reloaded.lifecycle, "disabled");
        assert!(!reloaded.enabled);
    })
    .await;
}
