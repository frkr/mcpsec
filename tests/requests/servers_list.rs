//! The registry listing is the app's home screen: if this query breaks, the
//! whole UI is dead. A missing column selected by the entity (an applied
//! migration edited in place) shows up here as a 500, which is exactly the
//! production failure this test pins down.

use loco_rs::testing::prelude::*;
use mcpsec::app::App;
use serde_json::Value;

use super::prepare_data;

async fn get_servers(request: &loco_rs::TestServer, token: &str, path: &str) -> (u16, Value) {
    let response = request
        .get(path)
        .add_header("authorization", format!("Bearer {token}"))
        .await;
    let status = response.status_code().as_u16();
    let body = serde_json::from_str(&response.text()).unwrap_or(Value::Null);
    (status, body)
}

#[tokio::test]
#[serial_test::serial]
async fn listing_servers_returns_the_page_envelope() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        // The exact query the SPA fires on the registry screen.
        let (status, body) = get_servers(
            &request,
            &logged_in.token,
            "/api/servers?page=1&page_size=20",
        )
        .await;

        assert_eq!(status, 200, "registry listing must not 5xx: {body}");
        for field in [
            "servers",
            "page",
            "page_size",
            "total_items",
            "filtered_items",
            "total_pages",
            "counts",
        ] {
            assert!(
                body.get(field).is_some(),
                "listing envelope missing {field:?}: {body}"
            );
        }
        assert!(body["servers"].is_array());
    })
    .await;
}

#[tokio::test]
#[serial_test::serial]
async fn listing_servers_works_on_every_lifecycle_filter() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        // Every tab the UI can select, plus the source filters the custom tab
        // uses. A broken column would fail on all of them.
        for query in [
            "lifecycle=all",
            "lifecycle=new",
            "lifecycle=active",
            "lifecycle=awaiting_review",
            "sync_source=registry",
            "sync_source=custom",
            "q=clickup",
        ] {
            let path = format!("/api/servers?page=1&page_size=20&{query}");
            let (status, body) = get_servers(&request, &logged_in.token, &path).await;
            assert_eq!(status, 200, "filter {query} failed: {body}");
        }
    })
    .await;
}

#[tokio::test]
#[serial_test::serial]
async fn acknowledge_new_is_idempotent() {
    request::<App, _, _>(|request, ctx| async move {
        let logged_in = prepare_data::init_user_login(&request, &ctx).await;
        for _ in 0..2 {
            let response = request
                .post("/api/servers/acknowledge-new")
                .add_header("authorization", format!("Bearer {}", logged_in.token))
                .await;
            assert_eq!(response.status_code(), 200, "{}", response.text());
            let body: Value = serde_json::from_str(&response.text()).unwrap();
            assert_eq!(body["ok"], true);
        }
    })
    .await;
}
