//! Postgres activation marker, persisted in the SQLite file itself.
//!
//! Triage marker: suppresses the NOVO badge once an operator has looked at a
//! freshly imported server (per row or via the bulk settings action).
//!
//! This lives in its own migration (not appended to
//! `m20261101_040000_server_custom_meta`) because that one had already been
//! applied in development: editing an applied migration in place silently
//! leaves the column missing while the entity selects it.

use loco_rs::schema::*;
use sea_orm_migration::prelude::*;

#[derive(DeriveMigrationName)]
pub struct Migration;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, m: &SchemaManager) -> Result<(), DbErr> {
        add_column(
            m,
            "mcp_servers",
            "acknowledged_at",
            ColType::TimestampWithTimeZoneNull,
        )
        .await
    }

    async fn down(&self, m: &SchemaManager) -> Result<(), DbErr> {
        remove_column(m, "mcp_servers", "acknowledged_at").await
    }
}
