import {useState} from 'react'
import {Link} from 'react-router'
import {useMutation, useQuery} from '@tanstack/react-query'
import {del, get, post, put} from '../api/client'
import type {ServerDetail} from '../bindings/ServerDetail'
import type {ServerSummary} from '../bindings/ServerSummary'
import {LifecycleBadge} from '../components/Badges'
import {useDebounced, useInvalidateAll} from '../layout/Layout'

/** The listing envelope: same shape the registry screen consumes. */
interface CustomServerPage {
    servers: ServerSummary[]
    page: number
    page_size: number
    total_items: number
    total_pages: number
    counts: Record<string, number>
}

interface FormState {
    registry_name: string
    title: string
    description: string
    version: string
    remote_url: string
}

/**
 * Lifecycles a server may be deleted from.
 *
 * Mirrors the allowlist in `mcp_servers::Model::delete_custom`: `active` may
 * back live proxy sessions, `awaiting_review` still owes a decision, and
 * `activating` has a worker holding the row. Keep the two in step.
 */
const DELETABLE = new Set(['new', 'rejected', 'disabled'])

const EMPTY_FORM: FormState = {
    registry_name: '',
    title: '',
    description: '',
    version: '1.0.0',
    remote_url: '',
}

/** Register-by-hand screen for MCP servers that are not in the official registry. */
export function CustomServers() {
    const [query, setQuery] = useState('')
    const [page, setPage] = useState(1)
    const debouncedQuery = useDebounced(query, 300)
    const [editing, setEditing] = useState<number | null>(null)
    const [form, setForm] = useState<FormState>(EMPTY_FORM)
    const [error, setError] = useState<string | null>(null)

    const list = useQuery({
        queryKey: ['custom-servers', debouncedQuery, page],
        queryFn: () => {
            const search = new URLSearchParams({
                page: String(page),
                page_size: '20',
            })
            if (debouncedQuery.trim() !== '') search.set('q', debouncedQuery.trim())
            return get<CustomServerPage>(`/api/custom-servers?${search.toString()}`)
        },
        placeholderData: (previous) => previous,
    })

    const invalidate = useInvalidateAll()

    /**
     * Enter edit mode, seeding the form from the row we already have.
     *
     * The seed happens here — on the click — and never from an effect watching
     * the query. A refetch (after any mutation, or a background poll) would
     * otherwise reset the fields mid-typing and silently discard the user's
     * edits.
     */
    function startEditing(s: ServerSummary) {
        setError(null)
        setEditing(s.id)
        setForm({
            registry_name: s.registry_name,
            title: s.title,
            description: s.description ?? '',
            version: s.version,
            remote_url: s.remote_url,
        })
    }

    function cancelEditing() {
        setEditing(null)
        setForm(EMPTY_FORM)
    }

    const create = useMutation({
        mutationFn: (payload: FormState) => post<ServerDetail>('/api/custom-servers', payload),
        onSuccess: () => {
            setError(null)
            setForm(EMPTY_FORM)
            invalidate()
        },
        onError: (err) => setError(err instanceof Error ? err.message : 'falha ao criar'),
    })

    const update = useMutation({
        mutationFn: ({id, payload}: { id: number; payload: Partial<FormState> }) =>
            put<ServerDetail>(`/api/custom-servers/${id}`, payload),
        onSuccess: () => {
            setError(null)
            cancelEditing()
            invalidate()
        },
        onError: (err) => setError(err instanceof Error ? err.message : 'falha ao salvar'),
    })

    const activate = useMutation({
        mutationFn: (id: number) => post<{ ok: boolean }>(`/api/custom-servers/${id}/activate`, {}),
        onSuccess: () => {
            setError(null)
            invalidate()
        },
        onError: (err) => setError(err instanceof Error ? err.message : 'falha ao ativar'),
    })

    const destroy = useMutation({
        mutationFn: (id: number) => del(`/api/custom-servers/${id}`),
        onSuccess: () => {
            setError(null)
            cancelEditing()
            invalidate()
        },
        onError: (err) => setError(err instanceof Error ? err.message : 'falha ao excluir'),
    })

    const items = list.data?.servers ?? []
    const totalItems = list.data?.total_items ?? 0
    const totalPages = list.data?.total_pages ?? 1

    function submit() {
        if (editing !== null) {
            update.mutate({
                id: editing,
                payload: {
                    title: form.title,
                    description: form.description,
                    version: form.version,
                    remote_url: form.remote_url,
                },
            })
        } else {
            create.mutate(form)
        }
    }

    return (
        <main className="page">
            <div className="spread">
                <div>
                    <h1>MCPs customizados</h1>
                    <p className="subtitle">
                        Servidores registrados manualmente — fora do registry oficial. Seguem o mesmo
                        workflow dos espelhados: ativar descobre e classifica as tools, e a revisão
                        aprova antes de virarem runnable.
                    </p>
                </div>
            </div>

            {error && <div className="error-box">{error}</div>}

            <div className="card" style={{marginBottom: 16}}>
                <h3 style={{marginTop: 0}}>{editing !== null ? 'Editar MCP' : 'Novo MCP customizado'}</h3>
                {editing !== null && (
                    <p className="muted" style={{marginTop: 0}}>
                        Editando <span className="mono">{form.registry_name}</span> —{' '}
                        <button type="button" className="small" onClick={cancelEditing}>
                            cancelar
                        </button>
                    </p>
                )}
                <form
                    onSubmit={(e) => {
                        e.preventDefault()
                        submit()
                    }}
                >
                    <label htmlFor="cs-registry-name">Identificador</label>
                    <input
                        id="cs-registry-name"
                        value={form.registry_name}
                        disabled={editing !== null}
                        placeholder="ex.: clickup"
                        onChange={(e) => setForm({...form, registry_name: e.target.value})}
                        required
                    />
                    <label htmlFor="cs-title">Título</label>
                    <input
                        id="cs-title"
                        value={form.title}
                        onChange={(e) => setForm({...form, title: e.target.value})}
                        required
                    />
                    <label htmlFor="cs-description">Descrição</label>
                    <input
                        id="cs-description"
                        value={form.description}
                        onChange={(e) => setForm({...form, description: e.target.value})}
                    />
                    <label htmlFor="cs-version">Versão</label>
                    <input
                        id="cs-version"
                        value={form.version}
                        onChange={(e) => setForm({...form, version: e.target.value})}
                        required
                    />
                    <label htmlFor="cs-remote-url">URL remota (https)</label>
                    <input
                        id="cs-remote-url"
                        type="url"
                        value={form.remote_url}
                        placeholder="https://mcp.exemplo.com/mcp"
                        onChange={(e) => setForm({...form, remote_url: e.target.value})}
                        required
                    />
                    <div className="row" style={{marginTop: 14}}>
                        <button type="submit" className="primary" disabled={create.isPending || update.isPending}>
                            {editing !== null ? 'Salvar' : 'Registrar'}
                        </button>
                    </div>
                </form>
            </div>

            <div className="toolbar">
                <input
                    placeholder="Buscar por identificador, título ou descrição…"
                    value={query}
                    onChange={(e) => {
                        setQuery(e.target.value)
                        setPage(1)
                    }}
                />
            </div>

            <div className="card">
                <div className="spread" style={{marginBottom: 8}}>
                    <span className="muted">{totalItems} servidor(es) customizado(s)</span>
                </div>
                {list.isFetching && !list.isPlaceholderData && (
                    <div className="muted" style={{padding: '8px 2px'}}>Carregando…</div>
                )}
                {!list.isFetching && items.length === 0 && (
                    <div className="muted" style={{padding: '8px 2px'}}>
                        Nenhum MCP customizado ainda — registre o primeiro acima.
                    </div>
                )}
                <div className="server-cards">
                    {items.map((s) => (
                        <div className="server-card" key={s.id}>
                            <div className="server-card-head">
                                <div>
                                    <div>{s.title}</div>
                                    <div className="mono muted">{s.registry_name}</div>
                                </div>
                                <div className="server-card-status">
                                    <LifecycleBadge lifecycle={s.lifecycle}/>
                                    <span className="mono muted">v{s.version}</span>
                                </div>
                            </div>
                            {s.description && (
                                <div className="server-card-desc">
                                    {s.description.length > 200
                                        ? `${s.description.slice(0, 200)}…`
                                        : s.description}
                                </div>
                            )}
                            <div className="mono muted" style={{marginTop: 4}}>{s.remote_url}</div>
                            {s.last_error && <div className="mono server-card-error">{s.last_error}</div>}
                            <div className="server-card-foot">
                                <div className="row">
                                    {(s.lifecycle === 'new' || s.lifecycle === 'rejected' || s.lifecycle === 'disabled') && (
                                        <button
                                            type="button"
                                            className="primary small"
                                            disabled={activate.isPending}
                                            onClick={() => activate.mutate(s.id)}
                                        >
                                            Ativar
                                        </button>
                                    )}
                                    {s.lifecycle === 'awaiting_review' && (
                                        <Link to={`/review/${s.id}`}>
                                            <button type="button" className="primary small">Revisar tools</button>
                                        </Link>
                                    )}
                                    {s.lifecycle === 'active' && (
                                        <Link to="/runner">
                                            <button type="button" className="small">Abrir runner</button>
                                        </Link>
                                    )}
                                    <button
                                        type="button"
                                        className="small"
                                        onClick={() => startEditing(s)}
                                    >
                                        Editar
                                    </button>
                                    {DELETABLE.has(s.lifecycle) && (
                                        <button
                                            type="button"
                                            className="small danger"
                                            disabled={destroy.isPending}
                                            onClick={() => {
                                                if (window.confirm(
                                                    `Excluir "${s.title}"? As tools descobertas e os grants de proxy associados serão removidos. A ação não pode ser desfeita.`,
                                                )) {
                                                    destroy.mutate(s.id)
                                                }
                                            }}
                                        >
                                            Excluir
                                        </button>
                                    )}
                                    <Link to={`/server/${s.id}`}>
                                        <button type="button" className="small">Detalhes</button>
                                    </Link>
                                </div>
                            </div>
                        </div>
                    ))}
                </div>
                {totalPages > 1 && (
                    <div className="pager">
                        <span className="muted">
                            página {list.data?.page ?? page} de {totalPages}
                        </span>
                        <div className="row">
                            <button type="button" className="small" disabled={page <= 1} onClick={() => setPage(page - 1)}>
                                Anterior
                            </button>
                            <button
                                type="button"
                                className="small"
                                disabled={page >= totalPages}
                                onClick={() => setPage(page + 1)}
                            >
                                Próxima
                            </button>
                        </div>
                    </div>
                )}
            </div>
        </main>
    )
}
